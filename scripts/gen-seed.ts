/**
 * Generates supabase/migrations/20261124000003_demo.sql and supabase/seed.sql from
 * src/lib/domain/demo-data.ts — the single source of truth for the demo shop.
 *
 *   npm run db:gen
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { buildDemoHistory, DEMO_CUSTOMERS, DEMO_PRODUCTS, DEMO_SHOP } from "../src/lib/domain/demo-data";

const root = path.resolve(__dirname, "..");

const catalog = {
  shop: DEMO_SHOP,
  products: DEMO_PRODUCTS.map((p) => ({
    code: p.code,
    name: p.name,
    name_ur: p.name_ur,
    base_unit: p.base_unit,
    pack: p.pack,
    price: p.price_rs * 100,
    cost: p.cost_rs * 100,
    stock_target: p.stock_target,
    reorder: p.reorder,
    aliases: p.aliases,
  })),
  customers: DEMO_CUSTOMERS,
};
const history = buildDemoHistory();
const aliasCount = DEMO_PRODUCTS.reduce((n, p) => n + p.aliases.length, 0);

const sql = `-- DukaanOS · 0003 · Demo shop seeding (GENERATED by scripts/gen-seed.ts — do not edit by hand)
-- ${DEMO_PRODUCTS.length} products · ${aliasCount} Urdu/Punjabi/Potohari/English aliases · ${DEMO_CUSTOMERS.length} customers (3 Alis, 2 Tariqs, Bilal)
-- ${history.length} historical events replayed through the real RPC cores so every row is hash-chained and balanced.

create or replace function private.demo_catalog() returns jsonb
language sql immutable set search_path = '' as $$ select $json$${JSON.stringify(catalog)}$json$::jsonb $$;

create or replace function private.demo_history() returns jsonb
language sql immutable set search_path = '' as $$ select $json$${JSON.stringify(history)}$json$::jsonb $$;

create or replace function private.seed_demo_shop(p_shop_id uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_cat jsonb := private.demo_catalog();
  v_p jsonb; v_c jsonb; v_pid uuid; v_alias text;
  v_pmap jsonb; v_cmap jsonb; v_ev jsonb; v_at timestamptz; v_n int := 0; v_lines jsonb; v_first timestamptz;
  v_day0 timestamp := date_trunc('day', now() at time zone 'Asia/Karachi');
begin
  for v_p in select value from jsonb_array_elements(v_cat->'products') loop
    insert into public.products (shop_id, sku_code, name, name_ur, base_unit, pack_size_base_units, unit_price_paisa,
                                 cost_price_paisa, reorder_level_base_units, created_at)
    values (p_shop_id, v_p->>'code', v_p->>'name', v_p->>'name_ur', v_p->>'base_unit', (v_p->>'pack')::bigint,
            (v_p->>'price')::bigint, (v_p->>'cost')::bigint, (v_p->>'reorder')::bigint, now() - interval '142 days')
    returning id into v_pid;
    for v_alias in select jsonb_array_elements_text(v_p->'aliases') loop
      insert into public.sku_aliases (shop_id, product_id, alias) values (p_shop_id, v_pid, lower(v_alias)) on conflict do nothing;
    end loop;
  end loop;

  for v_c in select value from jsonb_array_elements(v_cat->'customers') loop
    insert into public.customers (shop_id, code, name, role_tag, phone, aliases, created_at)
    values (p_shop_id, v_c->>'code', v_c->>'name', v_c->>'role_tag', v_c->>'phone',
            array(select lower(jsonb_array_elements_text(v_c->'aliases'))), now() - interval '120 days');
  end loop;

  select jsonb_object_agg(sku_code, id) into v_pmap from public.products where shop_id = p_shop_id;
  select jsonb_object_agg(code, id) into v_cmap from public.customers where shop_id = p_shop_id;

  for v_ev, v_at in
    select e,
           case when (e->'at') ? 'ago' then now() - make_interval(mins => (e->'at'->>'ago')::int)
                else ((v_day0 - make_interval(days => (e->'at'->>'d')::int) + make_interval(mins => (e->'at'->>'m')::int))
                      at time zone 'Asia/Karachi') end
    from jsonb_array_elements(private.demo_history()) e
    order by 2
  loop
    v_n := v_n + 1;
    v_first := coalesce(v_first, v_at);
    if v_ev->>'kind' = 'sale' then
      select coalesce(jsonb_agg(jsonb_build_object('product_id', v_pmap->>(l->>'p'), 'qty_base_units', l->'q',
                                                   'value_paisa', l->'v', 'spoken', null)), '[]'::jsonb)
      into v_lines from jsonb_array_elements(v_ev->'lines') l;
      perform private.commit_sale_core(p_shop_id, jsonb_build_object(
        'idempotency_key', 'seed-' || p_shop_id::text || '-' || v_n,
        'customer_id', v_cmap->>(v_ev->>'customer'),
        'lines', v_lines,
        'discount_paisa', coalesce((v_ev->>'disc')::bigint, 0),
        'cash_paid_paisa', v_ev->'cash',
        'audit_meta', jsonb_build_object('source', 'seed', 'channel', 'counter')), null, v_at);
    elsif v_ev->>'kind' = 'payment' then
      perform private.record_payment_core(p_shop_id, jsonb_build_object(
        'idempotency_key', 'seed-' || p_shop_id::text || '-' || v_n,
        'customer_id', v_cmap->>(v_ev->>'customer'),
        'amount_paisa', (v_ev->>'amount')::bigint,
        'audit_meta', jsonb_build_object('source', 'seed', 'channel', 'wasooli')), null, v_at);
    elsif v_ev->>'kind' = 'purchase' then
      select coalesce(jsonb_agg(jsonb_build_object('product_id', v_pmap->>(l->>'p'), 'qty_base_units', l->'q',
                                                   'line_total_paisa', l->'cost')), '[]'::jsonb)
      into v_lines from jsonb_array_elements(v_ev->'lines') l;
      perform private.record_purchase_core(p_shop_id, jsonb_build_object(
        'idempotency_key', 'seed-' || p_shop_id::text || '-' || v_n,
        'supplier_name', v_ev->>'supplier',
        'lines', v_lines,
        'cash_paid_paisa', (v_ev->>'cash')::bigint,
        'audit_meta', jsonb_build_object('source', 'seed', 'channel', 'parchi')), null, v_at);
    end if;
  end loop;

  -- opening stock so that the post-history shelf matches the catalog targets
  insert into public.inventory_movements (shop_id, product_id, delta_base_units, reason, created_at)
  select p_shop_id, p.id, (c->>'stock_target')::bigint - p.stock_base_units, 'opening', coalesce(v_first, now()) - interval '1 day'
  from public.products p join jsonb_array_elements(v_cat->'products') c on c->>'code' = p.sku_code
  where p.shop_id = p_shop_id and (c->>'stock_target')::bigint - p.stock_base_units <> 0;

  return jsonb_build_object('shop_id', p_shop_id, 'events', v_n,
    'products', (select count(*) from public.products where shop_id = p_shop_id),
    'aliases', (select count(*) from public.sku_aliases where shop_id = p_shop_id),
    'customers', (select count(*) from public.customers where shop_id = p_shop_id));
end $$;

-- Each judge gets an isolated, freshly seeded sandbox; the stage shop is a separate protected shop.
create or replace function public.create_demo_shop(p_user_id uuid, p_kind text default 'sandbox') returns uuid
language plpgsql security definer set search_path = '' as $$
declare v_id uuid; v_shop jsonb := private.demo_catalog()->'shop';
begin
  if p_kind not in ('sandbox', 'stage') then raise exception 'INVALID_KIND'; end if;
  insert into public.shops (name, owner_name, phone, city, is_demo_shop, is_stage_shop, active_since)
  values (v_shop->>'name', v_shop->>'owner_name', v_shop->>'phone', v_shop->>'city', true, p_kind = 'stage',
          now() - make_interval(days => (v_shop->>'active_since_days')::int))
  returning id into v_id;
  if p_user_id is not null then
    insert into public.shop_members (shop_id, user_id, role)
    values (v_id, p_user_id, case when p_kind = 'stage' then 'owner' else 'judge' end);
  end if;
  perform private.seed_demo_shop(v_id);
  insert into public.audit_events (shop_id, actor_id, event, payload) values (v_id, p_user_id, 'create_demo_shop', jsonb_build_object('kind', p_kind));
  return v_id;
end $$;

create or replace function public.link_shop_member(p_shop_id uuid, p_user_id uuid, p_role text default 'owner') returns void
language sql security definer set search_path = '' as $$
  insert into public.shop_members (shop_id, user_id, role) values (p_shop_id, p_user_id, p_role)
  on conflict (shop_id, user_id) do update set role = excluded.role;
$$;

-- Wipes and re-seeds a demo shop. Only callable with the service role (the API also checks DEMO_RESET_SECRET).
create or replace function public.reset_demo_shop(p_shop_id uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v jsonb;
begin
  if not exists (select 1 from public.shops where id = p_shop_id and is_demo_shop) then
    raise exception 'NOT_A_DEMO_SHOP';
  end if;
  perform private.lock_shop(p_shop_id);
  perform set_config('dukaan.maintenance', 'on', true);
  delete from public.idempotency_keys where shop_id = p_shop_id;
  delete from public.audit_events where shop_id = p_shop_id;
  delete from public.inventory_movements where shop_id = p_shop_id;
  delete from public.ledger_entries where shop_id = p_shop_id;
  delete from public.transaction_lines where shop_id = p_shop_id;
  delete from public.transactions where shop_id = p_shop_id;
  delete from public.sku_aliases where shop_id = p_shop_id;
  delete from public.products where shop_id = p_shop_id;
  delete from public.customers where shop_id = p_shop_id;
  perform set_config('dukaan.maintenance', 'off', true);
  v := private.seed_demo_shop(p_shop_id);
  insert into public.audit_events (shop_id, event, payload) values (p_shop_id, 'reset_demo_shop', v);
  return v;
end $$;

-- Addition: proves tamper-evidence live. Silently edits one historical ledger pair in a DEMO shop
-- (bypassing the append-only guard exactly like a malicious DBA would; the pair still sums to 0);
-- verify_ledger_chain then reports CHAIN_BROKEN at that row. reset_demo_shop restores the shop.
create or replace function public.demo_tamper(p_shop_id uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_row record;
begin
  if not exists (select 1 from public.shops where id = p_shop_id and is_demo_shop) then
    raise exception 'NOT_A_DEMO_SHOP';
  end if;
  select le.id, le.transaction_id, t.seq, le.amount_paisa into v_row
  from public.ledger_entries le join public.transactions t on t.id = le.transaction_id
  where le.shop_id = p_shop_id and le.account_code = '1010' and t.type = 'sale' and le.amount_paisa > 10000
  order by t.seq desc offset 3 limit 1;
  if v_row.id is null then raise exception 'NOTHING_TO_TAMPER'; end if;
  perform set_config('dukaan.maintenance', 'on', true);
  update public.ledger_entries set amount_paisa = amount_paisa - 10000 where id = v_row.id;
  update public.ledger_entries set amount_paisa = amount_paisa + 10000
  where transaction_id = v_row.transaction_id and account_code = '4010';
  perform set_config('dukaan.maintenance', 'off', true);
  insert into public.audit_events (shop_id, event, payload) values (p_shop_id, 'demo_tamper', jsonb_build_object('seq', v_row.seq));
  return jsonb_build_object('tampered_seq', v_row.seq, 'transaction_id', v_row.transaction_id, 'skimmed_paisa', 10000);
end $$;

revoke execute on function public.create_demo_shop(uuid, text) from public, anon, authenticated;
revoke execute on function public.link_shop_member(uuid, uuid, text) from public, anon, authenticated;
revoke execute on function public.reset_demo_shop(uuid) from public, anon, authenticated;
revoke execute on function public.demo_tamper(uuid) from public, anon, authenticated;
revoke execute on all functions in schema private from public, anon, authenticated;
grant execute on function public.create_demo_shop(uuid, text), public.link_shop_member(uuid, uuid, text),
  public.reset_demo_shop(uuid), public.demo_tamper(uuid) to service_role;
`;

writeFileSync(path.join(root, "supabase/migrations/20261124000003_demo.sql"), sql);

const seed = `-- DukaanOS canonical seed: the protected stage shop (Bismillah Kiryana) with
-- 3 Alis + 2 Tariqs + Bilal, ${aliasCount} dialect aliases and a ${history.length}-event history (14 dense days).
-- Public judges never touch this shop: each gets an isolated sandbox via create_demo_shop(user, 'sandbox').
-- scripts/setup.ts links stage@dukaanos.pk to it as owner.
select public.create_demo_shop(null, 'stage')
where not exists (select 1 from public.shops where is_stage_shop);
`;
writeFileSync(path.join(root, "supabase/seed.sql"), seed);

console.log(`wrote demo migration: ${DEMO_PRODUCTS.length} products, ${aliasCount} aliases, ${DEMO_CUSTOMERS.length} customers, ${history.length} events`);
